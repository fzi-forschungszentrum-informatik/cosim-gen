"""Build/run orchestration around the mk/*.mk engine. Each component gets its own sim
binary and remote-port channel; the whole design is built as one more unit."""

from __future__ import annotations

import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
from pathlib import Path

from . import paths
from .codegen import dts_overlay
from .codegen.main import processJson
from .config import Config
from .toolchain import ResolvedToolchain, resolve


def _write_if_changed(path: Path, content: str) -> None:
    # Keeps the mtime when unchanged; make rules use it as a staleness signal.
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def _run(cmd, **kw):
    print("+", " ".join(str(c) for c in cmd))
    subprocess.run([str(c) for c in cmd], check=True, **kw)


def _jobs(cfg: Config) -> str:
    return f"-j{cfg.jobs or os.cpu_count() or 1}"


def _require_tools(tools: ResolvedToolchain, names: list[str], cmd: str) -> None:
    missing = [name for name in names if tools[name] is None]
    if missing:
        hints = "\n".join(
            f"  {name}: set toolchain.{name} in cosim.json, the {name.upper()} env var, or install it on $PATH"
            for name in missing
        )
        raise RuntimeError(f"{cmd}: required tool(s) not found - {', '.join(missing)}\n{hints}")


def _design_top_name(design_input: Path) -> str:
    # Read from the input: design.hw.mlir doesn't exist yet when the Makefiles are written.
    text = design_input.read_text()
    if design_input.name.endswith(".mlir"):
        matches = re.findall(r"^\s*hw\.module\s+@(\w+)\(", text, re.MULTILINE)
        what = "public hw.module"
    else:
        matches = re.findall(r"^\s*circuit\s+(\w+)\s*:", text, re.MULTILINE)
        what = "circuit"
    uniq = list(dict.fromkeys(matches))
    if not uniq:
        raise RuntimeError(f"No {what} found in {design_input}")
    if len(uniq) > 1:
        raise RuntimeError(
            f"Multiple {what} names in {design_input} ({uniq}); "
            "specify a component in cosim.json to select one"
        )
    return uniq[0]


def _unit_spec(cfg: Config, comp, whole: bool, build_dir: Path) -> dict:
    """Build-graph entry for a declared component, or for the whole design when `whole`
    (`comp` is then soc_rtl or None)."""
    name = _design_top_name(cfg.design.input) if whole else comp.name
    return {
        "name": name,
        "dir": build_dir / "components" / name,
        "whole": whole,
        # cosim-extract renames an extracted component's top; the whole design keeps its own.
        "top_name": name if whole else comp.top_name,
        "path": "" if whole else comp.path,
        "io_regex": "" if whole else comp.io_regex,
        **cfg.settings_for(comp),
        "user_sim_cpp": comp is not None and comp.user_sim_cpp,
    }


def _render_common_mk(cfg: Config, tools: ResolvedToolchain, build_dir: Path,
                      design_hw_mlir: Path, verilator_root: str) -> str:
    """common.mk: the resolved toolchain and build-wide paths, included by every unit's
    config.mk and the top Makefile."""
    _MAKE_VARS = {
        "cosim_extract": "COSIM_EXTRACT",
        "qemu": "QEMU",
        "dtc": "DTC",
        "arcilator": "ARCILATOR",
        "firtool": "FIRTOOL",
        "verilator": "VERILATOR",
        "opt": "OPT",
        "llc": "LLC",
    }

    def _tool_var(name: str) -> str:
        # Unresolved tools get no line instead of a literal "None".
        path = tools[name]
        return f"{_MAKE_VARS[name]} := {path}" if path is not None else ""

    lines = [
        "# Regenerated by `cosim build` - do not edit; shared by every unit's",
        "# own config.mk (see mk/component.mk) and the top build/Makefile.",
        f"DESIGN_HW_MLIR := {design_hw_mlir}",
        f"LIBSYSTEMCTLM := {build_dir / 'systemctlm' / 'libsystemctlm.a'}",
        f"RTLGEN_INC_DIR := {paths.INCLUDE_DIR}",
        f"LIBSOC_DIR := {paths.LIBSYSTEMCTLM_SOC_DIR}",
        f"COSIM_MK_DIR := {paths.MK_DIR}",
        f"PYTHON := {sys.executable}",
        f"SYSTEMC_INCLUDE := {tools.require('systemc_include')}",
        f"SYSTEMC_LIBDIR := {tools.require('systemc_lib')}",
        # Must match the standard libsystemc was built with.
        "SYSTEMC_STD := c++17",
        _tool_var("cosim_extract"),
        _tool_var("qemu"),
        _tool_var("dtc"),
        _tool_var("arcilator"),
        _tool_var("firtool"),
        _tool_var("verilator"),
        f"VERILATOR_ROOT := {verilator_root}",
        _tool_var("opt"),
        _tool_var("llc"),
    ]
    return "\n".join(line for line in lines if line) + "\n"


def _render_config_mk(cfg: Config, unit: dict) -> str:
    # Escape make's "$" so the regex anchors survive.
    io = unit["io_regex"].replace("$", "$$")
    if unit["whole"]:
        io_flags = f"--config {cfg.path} --soc-rtl" if cfg.soc_rtl is not None else ""
    else:
        io_flags = f"--config {cfg.path} --component {unit['name']}"
    lines = [
        "# Regenerated by `cosim build` - do not edit.",
        # Relative: every unit sits at build/components/<name>/.
        "COMMON_MK := ../../common.mk",
        "include $(COMMON_MK)",
        f"SUPPORTED_BACKENDS := {' '.join(cfg.design.supported_backends)}",
        f"COMPONENT_NAME := {unit['name']}",
        f"COMPONENT_PATH := {unit['path']}",
        f"COMPONENT_IO := {io}",
        f"TOP_NAME := {unit['top_name']}",
        f"CONFIG_COMPONENT_FLAG := {io_flags}",
    ]
    return "\n".join(lines) + "\n"


def _make_value(value) -> str:
    """`value` as a make `:=` value: lists space-joined, bools as 1/0, "$" escaped."""
    if isinstance(value, bool):
        value = int(value)
    elif isinstance(value, list):
        value = " ".join(str(v) for v in value)
    return str(value).replace("$", "$$")


def _render_unit_makefile(unit: dict) -> str:
    settings = {
        "SYNC_QUANTUM": unit["sync_quantum"],
        "MAX_CYCLES": unit["max_cycles"],
        "RUN_ARGS": unit["extra_args"],
        "TRACE": unit["trace"],
        "SYSC_TRACE": unit["sysc_trace"],
        "VM_COVERAGE": unit["coverage"],
        "EXTRA_CXXFLAGS": unit["cxxflags"],
        "EXTRA_LDLIBS": unit["ldlibs"],
        "VERILATOR_EXTRA_ARGS": unit["verilator_args"],
        "ARCILATOR_ARGS": unit["arcilator_args"],
        "GENERATE_SIM_CPP": not unit["user_sim_cpp"],
    }
    lines = [
        f"# {unit['name']} build, regenerated by `cosim build` from cosim.json - do not edit.",
        "include config.mk",
        *(f"{k} := {_make_value(v)}" for k, v in settings.items()),
        "include $(COSIM_MK_DIR)/component.mk",
    ]
    return "\n".join(lines) + "\n"


def _render_qemu_makefile(cfg: Config) -> str:
    lines = [
        "# QEMU invocation, regenerated by `cosim build` from cosim.json - do not edit.",
        "include ../common.mk",
        f"ELFS := {_make_value(cfg.qemu.elfs)}",
        f"QEMU_EXTRA_ARGS := {_make_value(cfg.qemu.extra_args)}",
        f"SYNC_QUANTUM := {_make_value(cfg.sync_quantum)}",
        "include $(COSIM_MK_DIR)/qemu.mk",
    ]
    return "\n".join(lines) + "\n"


def _render_top_makefile(cfg: Config, tools: ResolvedToolchain, build_dir: Path,
                         units: list[dict]) -> str:
    """The top build/Makefile: lowers the design, builds libsystemctlm, then makes every unit."""
    # firrtl-keep-interfaces runs before cosim-extract's <type>_TOP rename.
    type_names = " ".join(c.type for c in cfg.components)

    lines = [
        "# Generated by `cosim build` - do not edit; re-run `cosim build`.",
        f"include {build_dir / 'common.mk'}",
        f"TLM_BUILD_DIR := {build_dir / 'systemctlm'}",
        ".DEFAULT_GOAL := all",
    ]
    if not cfg.design.lowered:
        # A make rule, so a .fir edit propagates to every unit.
        lines += [
            f"DESIGN_INPUT := {cfg.design.input}",
            f"COSIM_PLUGIN := {tools['cosim_plugin'] if type_names else ''}",
            f"ANNOTATION_FILE := {cfg.design.annotations or ''}",
            f"SEQMEM_FILE := {cfg.design.seqmem or ''}",
            f"COMPONENT_TYPE_NAMES := {type_names}",
            f"include {paths.MK_DIR / 'firtool.mk'}",
        ]
    lines.append(f"include {paths.MK_DIR / 'systemctlm.mk'}")

    unit_names = " ".join(u["name"] for u in units)
    lines += [
        f"UNITS := {unit_names}",
        ".PHONY: all $(UNITS)",
        "all: $(UNITS)",
        "$(UNITS): $(DESIGN_HW_MLIR) $(LIBSYSTEMCTLM)",
        # '+' shares the jobserver with each unit's sub-make.
        "\t+$(MAKE) -C components/$@",
    ]
    return "\n".join(lines) + "\n"


def _extra_files(cfg: Config) -> list[Path]:
    """Every component's and soc_rtl's extra_files, staged into build_dir."""
    files = [f for c in cfg.components for f in c.extra_files]
    if cfg.soc_rtl is not None:
        files += cfg.soc_rtl.extra_files
    return files


def _reject_basename_collisions(files: list[Path]) -> None:
    """Fails on two different files sharing one basename; the same file twice is fine."""
    staged: dict[str, Path] = {}
    for f in files:
        prior = staged.get(f.name)
        if prior is not None and prior.resolve() != f.resolve():
            raise RuntimeError(
                f"cosim.json: extra_files {prior} and {f} share the basename {f.name!r}"
            )
        staged[f.name] = f


def _build_tools(cfg: Config) -> list[str]:
    """The tools `cosim build` needs for the configured backends and input."""
    backends = cfg.design.supported_backends
    required = ["cosim_extract", "systemc_include", "systemc_lib"]
    # verilator's --split-verilog needs firtool even for a lowered input.
    if not cfg.design.lowered or "verilator" in backends:
        required.append("firtool")
    # firrtl-keep-interfaces only runs when lowering with components.
    if not cfg.design.lowered and cfg.components:
        required.append("cosim_plugin")
    if "arcilator" in backends:
        required += ["arcilator", "opt", "llc"]
    if "verilator" in backends:
        required.append("verilator")
    return required


def build(cfg: Config, generate_only: bool = False) -> int:
    build_dir = cfg.root / "build"
    build_dir.mkdir(parents=True, exist_ok=True)
    tools = resolve(cfg.toolchain)

    _require_tools(tools, _build_tools(cfg), "cosim build")

    # firtool resolves MemoryFileInlineAnnotation filenames against build_dir.
    _reject_basename_collisions(_extra_files(cfg))
    for f in _extra_files(cfg):
        shutil.copy2(f, build_dir / f.name)

    design_hw_mlir = cfg.design.input if cfg.design.lowered else build_dir / "design.hw.mlir"

    verilator_root = ""
    if "verilator" in cfg.design.supported_backends:
        verilator_root = subprocess.run(
            [str(tools.require("verilator")), "--getenv", "VERILATOR_ROOT"],
            check=True, capture_output=True, text=True,
        ).stdout.strip()

    _write_if_changed(
        build_dir / "common.mk",
        _render_common_mk(cfg, tools, build_dir, design_hw_mlir, verilator_root),
    )

    # One unit per component, plus one for the whole design (soc_rtl).
    units = []
    for comp, whole in [(c, False) for c in cfg.components] + [(cfg.soc_rtl, True)]:
        unit = _unit_spec(cfg, comp, whole, build_dir)
        units.append(unit)
        unit["dir"].mkdir(parents=True, exist_ok=True)
        for f in (comp.extra_files if comp is not None else []):
            shutil.copy2(f, unit["dir"] / f.name)
        _write_if_changed(unit["dir"] / "config.mk", _render_config_mk(cfg, unit))
        _write_if_changed(unit["dir"] / "Makefile", _render_unit_makefile(unit))

    qemu_dir = build_dir / "qemu"
    qemu_dir.mkdir(parents=True, exist_ok=True)
    _write_if_changed(qemu_dir / "Makefile", _render_qemu_makefile(cfg))

    top_makefile = build_dir / "Makefile"
    top_makefile.write_text(_render_top_makefile(cfg, tools, build_dir, units))

    overlay_components = [c.name for c in cfg.components if any(i.NEEDS_QEMU for i in c.interfaces)]
    if overlay_components and cfg.design.dts:
        (build_dir / "cosim_components.json").write_text(json.dumps(overlay_components) + "\n")

    if generate_only:
        return 0

    _run(["make", "-f", top_makefile, _jobs(cfg), "all"], cwd=build_dir)

    for unit in units:
        for backend in cfg.design.supported_backends:
            print(f"Built {unit['dir'] / f'build-{backend}' / 'sim'}")

    return 0


def _component_typed_io(comp, comp_dir: Path, backend: str):
    # IO classification doesn't depend on the backend; any built one's state json works.
    state_json = comp_dir / f"build-{backend}" / f"{comp.name}.json"
    if not state_json.exists():
        raise RuntimeError(f"{state_json} not found - run 'cosim build' first")
    models = processJson(state_json, io_spec=comp)
    assert len(models) == 1, f"component {comp.name}: expected exactly one top module in its state json"
    return models[0].typedIO


def _gen_dtb(cfg: Config, tools: ResolvedToolchain, build_dir: Path, comp_names: list[str] | None,
             backend: str) -> Path:
    """Writes build/cosim.dts and returns its compiled dtb: design.dts plus the overlays of
    `comp_names` (none if None), with IO classified from `backend`'s state json."""
    if not cfg.design.dts:
        raise RuntimeError("this needs design.dts (a base platform device tree) to build the DTB from.")
    cosim_dts = build_dir / "cosim.dts"
    overlay_paths: list[str] = []
    if comp_names:
        tree, sys_bus = dts_overlay.open_base_tree(
            str(cfg.design.dts), tools["dtc"]
        )
        for name in comp_names:
            comp = cfg.component(name)
            unit_dir = build_dir / "components" / name
            typed_io = _component_typed_io(comp, unit_dir, backend)
            overlay_dts = dts_overlay.gen_component_dts(name, comp, typed_io, tree, sys_bus)
            overlay_path = unit_dir / "overlay.dts"
            overlay_path.write_text(overlay_dts)
            overlay_paths.append(str(overlay_path.relative_to(build_dir)))
    cosim_dts.write_text(dts_overlay.gen_run_dts(cfg.design.dts.name, overlay_paths))
    dtb = cosim_dts.with_suffix(".dtb")
    _run(["make", "-C", build_dir / "qemu", dtb, f"DTS_INCLUDE_DIR={cfg.design.dts.parent}",
          f"DTC={tools['dtc']}"])
    return dtb


def _run_coupled(cfg: Config, tools: ResolvedToolchain, build_dir: Path, dtb: Path, comp_names: list[str],
                 backend: str) -> int:
    # One sim per component, each on its own remote-port socket under one machine path.
    machine_path = Path(tempfile.mkdtemp(prefix="qemu-cosim."))
    procs = []
    try:
        sync_quantums = []
        for name in comp_names:
            unit = _unit_spec(cfg, cfg.component(name), False, build_dir)
            sync_quantums.append(unit["sync_quantum"])
            # QEMU's rp_autocreate_chardev() naming.
            sock = machine_path / f"qemu-rport-{name.lower()}"
            cmd = ["make", "-C", str(unit["dir"]), "run-coupled", f"SOCK={sock}", f"BACKEND={backend}"]
            print("+", " ".join(cmd))
            # Own process group, so the cleanup below also kills the sim under make.
            procs.append(subprocess.Popen(cmd, start_new_session=True))

        # QEMU syncs as often as the tightest component sync_quantum.
        _run(["make", "-C", str(build_dir / "qemu"), "run-qemu-coupled", f"QEMU={tools['qemu']}",
              f"DTB={dtb}", f"MACHINE_PATH={machine_path}", f"LOG={build_dir / 'run.log'}",
              f"SYNC_QUANTUM={min(sync_quantums)}"])
    finally:
        for p in procs:
            try:
                os.killpg(p.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        for p in procs:
            p.wait()
        shutil.rmtree(machine_path, ignore_errors=True)
    return 0


def run(cfg: Config, mode: str, components: list[str] | None = None, backend: str | None = None) -> int:
    build_dir = cfg.root / "build"
    tools = resolve(cfg.toolchain)
    components = components or []
    backend = backend or cfg.design.supported_backends[0]
    if backend not in cfg.design.supported_backends:
        raise RuntimeError(
            f"backend {backend!r} isn't in design.supported_backends "
            f"({', '.join(cfg.design.supported_backends)})"
        )
    if mode != "rtl":
        _require_tools(tools, ["qemu", "dtc"], "cosim run")

    if mode == "rtl":
        if len(components) > 1:
            raise RuntimeError("'rtl' mode runs one target standalone - pass at most one component name.")
        if components:
            unit = _unit_spec(cfg, cfg.component(components[0]), False, build_dir)
        else:
            unit = _unit_spec(cfg, cfg.soc_rtl, True, build_dir)
        _run(["make", "-C", unit["dir"], _jobs(cfg), "run", f"BACKEND={backend}"])
        return 0

    if mode == "qemu":
        if not components:
            # Plain boot: design.dts as-is, no RTL coupling.
            dtb = _gen_dtb(cfg, tools, build_dir, None, backend)
            _run(["make", "-C", str(build_dir / "qemu"), "run-qemu", f"QEMU={tools['qemu']}",
                  f"DTB={dtb}", f"LOG={build_dir / 'run.log'}"])
            return 0

        # Only these components' overlays, or QEMU waits on sockets nobody serves.
        for name in components:
            typed_io = _component_typed_io(cfg.component(name), build_dir / "components" / name, backend)
            if not typed_io.needs_qemu:
                raise RuntimeError(f"{name!r} has no bus/interrupt/gpio IO - use `cosim run rtl {name}` instead.")
        dtb = _gen_dtb(cfg, tools, build_dir, components, backend)
        return _run_coupled(cfg, tools, build_dir, dtb, components, backend)

    # mode == "cosim": every component that needs QEMU; COMPONENT args are ignored.
    manifest_path = build_dir / "cosim_components.json"
    if not manifest_path.exists():
        raise RuntimeError(
            "No components need QEMU coupling (no bus/interrupt IO) - use `cosim run rtl` "
            "or `cosim run` (a plain boot) instead."
        )
    comp_names = json.loads(manifest_path.read_text())
    dtb = _gen_dtb(cfg, tools, build_dir, comp_names, backend)
    return _run_coupled(cfg, tools, build_dir, dtb, comp_names, backend)


def clean(cfg: Config, all: bool = False) -> int:
    build_dir = cfg.root / "build"
    if all or not build_dir.exists():
        _run(["rm", "-rf", build_dir])
        return 0

    # Keeps sim.cpp and own sources; --all removes them too.
    targets = [
        build_dir / "Makefile",
        build_dir / "qemu",
        build_dir / "common.mk",
        build_dir / "design.hw.mlir",
        build_dir / "systemctlm",
        build_dir / "cosim.dts",
        build_dir / "cosim.dtb",
        build_dir / "cosim_components.json",
        build_dir / "run.log",
    ]
    targets += [build_dir / f.name for f in _extra_files(cfg)]
    components_dir = build_dir / "components"
    if components_dir.is_dir():
        for unit_dir in sorted(components_dir.iterdir()):
            targets += [unit_dir / "Makefile", unit_dir / "config.mk", unit_dir / "overlay.dts"]
            for entry in sorted(unit_dir.iterdir()):
                if entry.is_dir() and entry.name.startswith("build-"):
                    targets.append(entry)
    _run(["rm", "-rf", *targets])
    return 0
